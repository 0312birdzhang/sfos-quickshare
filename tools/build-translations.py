"""Validate shared catalogs and generate a file-I/O-free QML translation module."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
catalogs = {p.stem: json.loads(p.read_text(encoding='utf8')) for p in sorted((ROOT/'quickshare/locales').glob('*.json'))}
base = catalogs['en']
for locale, entries in catalogs.items():
    assert entries.keys() == base.keys(), 'Incomplete catalog: ' + locale
    for key, value in entries.items():
        assert value.strip(), (locale, key)
        assert sorted(re.findall(r'%[1-9][0-9]*', key)) == sorted(re.findall(r'%[1-9][0-9]*', value)), (locale, key)
script = '''.pragma library
// Generated by tools/build-translations.py from quickshare/locales/*.json.
var catalogs = CATALOGS;
function language(value) {
    value = String(value || "en").split(".")[0].split("@")[0].replace(/-/g, "_");
    if (value.toLowerCase().indexOf("zh") === 0)
        return /tw|hk|mo|hant/i.test(value) ? "zh_TW" : "zh_CN";
    var code = value.split("_")[0].toLowerCase();
    return /^(en|de|fr|ru)$/.test(code) ? code : "en";
}
function translate(message, args, locale) {
    var entries = catalogs[language(locale)] || catalogs.en;
    var text = entries[message] || message;
    return text.replace(/%([1-9][0-9]*)/g, function(match, index) {
        return Number(index) <= args.length ? String(args[Number(index)-1]) : match;
    });
}
function tr(message) {
    return translate(message, Array.prototype.slice.call(arguments, 1), Qt.locale().name);
}
'''.replace('CATALOGS', json.dumps(catalogs, ensure_ascii=True, sort_keys=True))
(ROOT/'qml/QuickShareI18n.js').write_text(script, encoding='utf8', newline='\n')
print('Validated', len(base), 'messages in', ', '.join(catalogs))
